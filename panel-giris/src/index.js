/**
 * QZEN DİZAYN panel girişi: Cloudflare Worker (ücretsiz plan).
 *
 * The admin panel (Sveltia CMS, /admin on the site) signs in here with a username and password
 * instead of a GitHub account, so the people editing the site never need one.
 *
 *   GET  /auth          The sign-in window the panel opens (Sveltia's OAuth popup protocol).
 *   POST /login         Checks the password; on success hands the panel a signed session token.
 *   *    /api/v3/...    The panel's GitHub REST calls, forwarded to api.github.com
 *   POST /api/graphql  and its GraphQL calls, both with the site's GitHub key added here.
 *
 * The GitHub key (GITHUB_TOKEN: a fine-grained token limited to this one repository's contents)
 * never leaves Cloudflare. Browsers only hold a session token, checked against the user list on
 * every request, so removing a user or changing a password cuts that person off at once.
 *
 * Secrets (wrangler secret put): GITHUB_TOKEN, SESSION_KEY (random), USERS (JSON, see kullanici.mjs).
 * Vars (wrangler.toml): ALLOWED_DOMAINS, REPO. KV binding LOGIN_LIMIT throttles wrong passwords.
 */

const SESSION_DAYS = 180;
const MAX_FAILS = 5; // wrong passwords per username (and per IP) ...
const LOCK_SECONDS = 15 * 60; // ... before a 15-minute pause

const enc = new TextEncoder();

// ---------------------------------------------------------------------------------------------
// Small helpers

const b64url = (bytes) =>
  btoa(String.fromCharCode(...new Uint8Array(bytes)))
    .replaceAll("+", "-")
    .replaceAll("/", "_")
    .replace(/=+$/, "");

const hex = (bytes) => [...new Uint8Array(bytes)].map((b) => b.toString(16).padStart(2, "0")).join("");

const sha256 = async (text) => hex(await crypto.subtle.digest("SHA-256", enc.encode(text)));

/** Constant-time comparison of two strings of hex/base64url characters. */
const same = (a, b) => {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
};

const hmac = async (key, text) => {
  const k = await crypto.subtle.importKey("raw", enc.encode(key), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  return b64url(await crypto.subtle.sign("HMAC", k, enc.encode(text)));
};

const escapeHTML = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

const domainPatterns = (env) =>
  (env.ALLOWED_DOMAINS ?? "")
    .split(",")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => `^${d.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replaceAll("\\*", ".+")}$`);

const isAllowedHost = (env, host) => domainPatterns(env).some((p) => new RegExp(p).test(host ?? ""));

const isAllowedOrigin = (env, origin) => {
  try {
    return isAllowedHost(env, new URL(origin).hostname);
  } catch {
    return false;
  }
};

/** USERS secret: { "ibrahim": { "name": "İbrahim Aydın", "salt": "…", "hash": "sha256(salt + password)" } } */
const users = (env) => {
  try {
    return JSON.parse(env.USERS ?? "{}");
  } catch {
    return {};
  }
};

// Passwords are long random strings generated by kullanici.mjs, so a salted SHA-256 is enough
// (a slow hash would also break the free plan's 10 ms CPU limit); guessing is stopped by the lock.
const checkPassword = async (user, password) => !!user && same(await sha256(user.salt + password), user.hash);

// ---------------------------------------------------------------------------------------------
// Session tokens: "<username>.<expiry>.<password fingerprint>.<signature>"

const fingerprint = (user) => user.hash.slice(0, 12);

const issueSession = async (env, username, user) => {
  const expiry = Math.floor(Date.now() / 1000) + SESSION_DAYS * 86400;
  const body = `${username}.${expiry}.${fingerprint(user)}`;
  return `qzen.${body}.${await hmac(env.SESSION_KEY, body)}`;
};

/** The username of a valid session, or null. A removed user or a changed password fails here. */
const readSession = async (env, token) => {
  const parts = (token ?? "").split(".");
  if (parts.length !== 5 || parts[0] !== "qzen") return null;
  const [, username, expiry, print, signature] = parts;
  const body = `${username}.${expiry}.${print}`;
  if (!same(await hmac(env.SESSION_KEY, body), signature)) return null;
  if (Number(expiry) < Date.now() / 1000) return null;
  const user = users(env)[username];
  if (!user || fingerprint(user) !== print) return null;
  return username;
};

// ---------------------------------------------------------------------------------------------
// Wrong-password lock (KV, eventually consistent, which is fine for slowing down guessing)

const failKeys = (username, ip) => [`u:${username}`, `ip:${ip}`];

const isLocked = async (env, username, ip) => {
  if (!env.LOGIN_LIMIT) return false;
  const counts = await Promise.all(failKeys(username, ip).map((k) => env.LOGIN_LIMIT.get(k)));
  return counts.some((c) => Number(c) >= MAX_FAILS);
};

const recordFail = async (env, username, ip) => {
  if (!env.LOGIN_LIMIT) return;
  await Promise.all(
    failKeys(username, ip).map(async (k) => {
      const n = Number(await env.LOGIN_LIMIT.get(k)) + 1;
      await env.LOGIN_LIMIT.put(k, String(n), { expirationTtl: LOCK_SECONDS });
    }),
  );
};

